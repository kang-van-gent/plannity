const t = (text: string, mark: Partial<Record<'bold' | 'italic' | 'code', boolean>> = {}): BlogInline => ({ type: 'text', text, ...mark })
const p = (...children: (string | BlogInline)[]): BlogBlock => ({ type: 'paragraph', children: children.map((c) => (typeof c === 'string' ? t(c) : c)) })
const h = (text: string, level: 2 | 3 = 2): BlogBlock => ({ type: 'heading', level, children: [t(text)] })
const ul = (...items: string[]): BlogBlock => ({ type: 'list', format: 'unordered', children: items.map((i) => ({ type: 'list-item', children: [t(i)] })) })
const ol = (...items: string[]): BlogBlock => ({ type: 'list', format: 'ordered', children: items.map((i) => ({ type: 'list-item', children: [t(i)] })) })
const quote = (text: string): BlogBlock => ({ type: 'quote', children: [t(text)] })

